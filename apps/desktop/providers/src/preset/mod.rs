#[allow(clippy::too_many_arguments)]
const fn preset(
    slug: &'static str,
    label: &'static str,
    category: &'static str,
    kind: ProviderKind,
    default_url: &'static str,
    api_key_required: bool,
    allow_private_default: bool,
    notes: &'static str,
) -> ProviderPreset {
    ProviderPreset {
        slug,
        label,
        category,
        kind,
        default_url,
        api_key_required,
        allow_private_default,
        notes,
    }
}

pub fn by_slug(slug: &str) -> Option<&'static ProviderPreset> {
    PRESETS.iter().find(|p| p.slug == slug)
}

/// True for a preset that targets a runtime the user can host on their own
/// machine (Ollama, LM Studio, vLLM, llama.cpp, …).
///
/// The catalogue's `category` is the single source of truth, so a new local
/// preset does not have to be added to a second hard-coded list in the Auto
/// router. Callers still need [`crate::discovery::is_local_base_url`] for a
/// provider row that points at the machine's actual base URL: a preset only
/// says what kind of runtime it is, not where it is running.
pub fn is_local_slug(slug: &str) -> bool {
    by_slug(slug).is_some_and(|preset| preset.category == "ローカル")
}

impl ProviderKind {
    pub fn as_str(&self) -> &'static str {
        match self {
            ProviderKind::OpenAI => "openai",
            ProviderKind::Anthropic => "anthropic",
            ProviderKind::Gemini => "gemini",
            ProviderKind::OpenRouter => "openrouter",
            ProviderKind::Ollama => "ollama",
            ProviderKind::LMStudio => "lmstudio",
            ProviderKind::Compatible => "compatible",
        }
    }

    pub fn parse(value: &str) -> Option<Self> {
        match value {
            "openai" => Some(Self::OpenAI),
            "anthropic" => Some(Self::Anthropic),
            "gemini" => Some(Self::Gemini),
            "openrouter" => Some(Self::OpenRouter),
            "ollama" => Some(Self::Ollama),
            "lmstudio" => Some(Self::LMStudio),
            "compatible" => Some(Self::Compatible),
            _ => None,
        }
    }

    /// Default embedding model for this transport.
    ///
    /// `None` means the transport has no embeddings endpoint at all — Anthropic
    /// is the only one, and its adapter keeps [`Provider::embed`]'s default
    /// `EmbeddingNotSupported` answer. The value is only a default: a provider
    /// row may override it with `data.embeddingModel` (or
    /// `data.extra.embeddingModel`), which is how a local Ollama with a
    /// different model pulled, or a gateway that renames the OpenAI models,
    /// stays usable.
    ///
    /// [`Provider::embed`]: crate::Provider::embed
    pub fn default_embedding_model(&self) -> Option<&'static str> {
        match self {
            Self::OpenAI | Self::OpenRouter | Self::Compatible => Some("text-embedding-3-small"),
            Self::Gemini => Some("text-embedding-004"),
            Self::Ollama => Some("nomic-embed-text"),
            Self::LMStudio => Some("text-embedding-nomic-embed-text-v1.5"),
            Self::Anthropic => None,
        }
    }
}

/// Default embedding model for a stored `providers.data.kind` string.
///
/// `None` both for an unknown kind and for a transport that has no embeddings
/// endpoint; callers must then skip the provider rather than attempt a call.
pub fn default_embedding_model(kind: &str) -> Option<&'static str> {
    ProviderKind::parse(kind).and_then(|kind| kind.default_embedding_model())
}
