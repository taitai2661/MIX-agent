import { useSyncExternalStore } from "react";

export type Language = "ja" | "en";
const key = "mix-agent-language";
const listeners = new Set<() => void>();

export function browserLanguage(languages: readonly string[] = typeof navigator === "undefined" ? [] : navigator.languages): Language {
  for (const value of languages) {
    const code = value.toLowerCase().split("-")[0];
    if (code === "ja" || code === "en") return code;
  }
  return "ja";
}

function initialLanguage(): Language {
  if (typeof document === "undefined") return "ja";
  const saved = typeof localStorage === "undefined" ? null : localStorage.getItem(key);
  return saved === "ja" || saved === "en" ? saved : browserLanguage();
}

let language: Language = initialLanguage();
if (typeof document !== "undefined") document.documentElement.lang = language;

export function getLanguage() { return language; }
export function setLanguage(value: Language) {
  if (language === value) return;
  language = value;
  if (typeof localStorage !== "undefined") localStorage.setItem(key, value);
  if (typeof document !== "undefined") document.documentElement.lang = value;
  listeners.forEach(listener => listener());
}
export function useLanguage() {
  return useSyncExternalStore(listener => { listeners.add(listener); return () => { listeners.delete(listener); }; }, getLanguage, getLanguage);
}

